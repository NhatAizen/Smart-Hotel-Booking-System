package com.smarthotel.ai.assistant.v2.service;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.smarthotel.ai.assistant.v2.dto.NearbyLocation;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.core.io.ClassPathResource;
import org.springframework.http.client.SimpleClientHttpRequestFactory;
import org.springframework.stereotype.Component;
import org.springframework.web.client.RestClient;
import java.net.URI;
import java.time.Duration;
import java.util.*;

/** Map facts are looked up, never generated by the language model. */
@Component
public class LandmarkResolver {
    public record Resolution(String status, List<NearbyLocation> choices) {}
    private record Cached(long at, Resolution result) {}
    private record Candidate(NearbyLocation point,JsonNode properties) {}
    private final RestClient client;
    private final boolean enabled;
    private final JsonNode local;
    private final Map<String,Cached> cache=new LinkedHashMap<>();
    private long lastRequest;

    public LandmarkResolver() {this(false,"https://photon.komoot.io");}

    @Autowired
    public LandmarkResolver(@Value("${app.places.enabled:true}") boolean enabled,
            @Value("${app.places.base-url:https://photon.komoot.io}") String baseUrl) {
        URI uri=URI.create(baseUrl);
        if(uri.getUserInfo()!=null || !("https".equals(uri.getScheme()) || Set.of("localhost","127.0.0.1","place-service").contains(uri.getHost())))
            throw new IllegalArgumentException("Place lookup requires HTTPS or an internal service");
        this.enabled=enabled;
        var factory=new SimpleClientHttpRequestFactory();
        factory.setConnectTimeout(Duration.ofSeconds(2)); factory.setReadTimeout(Duration.ofSeconds(4));
        client=RestClient.builder().baseUrl(baseUrl).requestFactory(factory)
                .defaultHeader("User-Agent","EnziuRooms/1.0 (https://enziurooms.xyz)").build();
        try(var stream=new ClassPathResource("landmarks.json").getInputStream()) {local=new ObjectMapper().readTree(stream);}
        catch(java.io.IOException failure){throw new IllegalStateException("Verified landmark data unavailable",failure);}
    }

    public synchronized Resolution resolve(NearbyLocation requested, String cityHint) {
        String query=norm(requested.query());
        double radius=requested.radiusKm()==null?5:requested.radiusKm();
        if(query.isBlank() || query.length()>160 || !Double.isFinite(radius) || radius<.1 || radius>100)
            return new Resolution("UNKNOWN",List.of());
        // A region alias alone cannot identify a POI named after that region.
        if(CityNames.regionOnly(query)) return new Resolution("AMBIGUOUS",List.of());
        for(JsonNode item:local) {
            boolean alias=false;
            for(JsonNode value:item.path("aliases")) {
                String known=norm(value.asText());
                if(query.equals(known) || !tokens(known).isEmpty() && tokens(query).equals(tokens(known))) alias=true;
            }
            if(!alias && !query.equals(norm(item.path("name").asText()))) continue;
            var point=new NearbyLocation(requested.query(),radius,item.path("name").asText(),item.path("latitude").asDouble(),item.path("longitude").asDouble(),item.path("sourceUrl").asText());
            boolean explicitAirport=false;
            for(JsonNode qualifier:item.path("qualifiers")) if(query.contains(norm(qualifier.asText()))) explicitAirport=true;
            boolean localHint=CityNames.same(cityHint,item.path("city").asText());
            if(explicitAirport || localHint) return new Resolution("FOUND",List.of(point));
            if(cityHint==null || cityHint.isBlank()) return new Resolution("AMBIGUOUS",List.of(point));
        }
        var meaningful=tokens(query);
        if(meaningful.isEmpty()) return new Resolution("AMBIGUOUS",List.of());
        String key=query+"|"+CityNames.canonical(cityHint);
        long now=System.currentTimeMillis();
        Cached saved=cache.get(key);
        if(saved!=null && now-saved.at()< ("FOUND".equals(saved.result().status())?86_400_000:120_000))
            return resize(saved.result(),requested);
        if(!enabled) return new Resolution("UNAVAILABLE",List.of());
        // Moderate, user-triggered use only. Cache results and never autocomplete.
        if(now-lastRequest<1000) return new Resolution("UNAVAILABLE",List.of());
        lastRequest=now;
        Resolution result;
        try {
            String lookup=query.replaceFirst("^(?:nha ga|ga)\\s+(?=t?\\d+\\b)","terminal ");
            if(cityHint!=null && !cityHint.isBlank()) lookup+=", "+cityHint;
            final String search=lookup;
            JsonNode body=client.get().uri(builder->builder.path("/api/").queryParam("q",search)
                    .queryParam("limit",12).queryParam("lang","en").queryParam("countrycode","VN").build()).retrieve().body(JsonNode.class);
            if(body==null || !body.path("features").isArray()) throw new org.springframework.web.client.RestClientException("Invalid place data");
            var candidates=new ArrayList<Candidate>();
            for(JsonNode feature:body.path("features")) {
                var properties=feature.path("properties"); var coords=feature.path("geometry").path("coordinates");
                if(!"VN".equalsIgnoreCase(properties.path("countrycode").asText()) || !"Point".equals(feature.path("geometry").path("type").asText()) || coords.size()!=2) continue;
                double lon=coords.get(0).asDouble(Double.NaN), lat=coords.get(1).asDouble(Double.NaN);
                if(!valid(lat,lon)) continue;
                if(!kindMatches(query,properties)) continue;
                String region=java.util.stream.Stream.of("city","state","county","district","locality")
                        .map(keyName->CityNames.canonical(properties.path(keyName).asText(""))).collect(java.util.stream.Collectors.joining(", "));
                if(cityHint!=null && !cityHint.isBlank() && !CityNames.inAddress(region,cityHint)) continue;
                String name=properties.path("name").asText("");
                var nameTokens=tokens(norm(name+" "+properties.path("ref").asText("")));
                var actual=tokens(norm(name+" "+region+" "+properties.path("street").asText("")));
                // Require explicit name/code evidence. A city/address-only hit is not the POI.
                long overlap=meaningful.stream().filter(actual::contains).count();
                boolean codes=meaningful.stream().filter(t->t.matches("[a-z]+\\d+|\\d+[a-z]+"))
                        .allMatch(nameTokens::contains);
                if(name.isBlank() || !codes || meaningful.stream().noneMatch(nameTokens::contains) || overlap < Math.max(1,Math.ceil(meaningful.size()*.6))) continue;
                String city=properties.path("city").asText(properties.path("state").asText(""));
                String display=name+(city.isBlank()?"":", "+city);
                String osmType=Map.of("N","node","W","way","R","relation").get(properties.path("osm_type").asText());
                long id=properties.path("osm_id").asLong(0);
                if(osmType==null || id<=0) continue;
                var point=new NearbyLocation(requested.query(),radius,display,lat,lon,"https://www.openstreetmap.org/"+osmType+"/"+id);
                if(candidates.stream().noneMatch(p->p.point().sourceUrl().equals(point.sourceUrl()))) candidates.add(new Candidate(point,properties));
            }
            if(candidates.size()>1) {
                // A named whole building may contain floor/entrance nodes. Only
                // an enclosing provider footprint establishes that identity.
                var possible=List.copyOf(candidates);
                var enclosing=possible.stream().filter(c->"W".equals(c.properties().path("osm_type").asText())
                        && possible.stream().allMatch(other->contains(c.properties().path("extent"),other.point()))).toList();
                if(enclosing.size()==1) candidates=new ArrayList<>(enclosing);
            }
            var choices=candidates.stream().map(Candidate::point).toList();
            result=new Resolution(choices.size()==1?"FOUND":choices.isEmpty()?"UNKNOWN":"AMBIGUOUS",List.copyOf(choices));
        } catch(org.springframework.web.client.RestClientException failure) {result=new Resolution("UNAVAILABLE",List.of());}
        if(cache.size()>=128) cache.remove(cache.keySet().iterator().next());
        cache.put(key,new Cached(now,result));
        return result;
    }

    private static Resolution resize(Resolution resolution, NearbyLocation request) {
        return new Resolution(resolution.status(),resolution.choices().stream().map(p->new NearbyLocation(request.query(),request.radiusKm(),p.displayName(),p.latitude(),p.longitude(),p.sourceUrl())).toList());
    }
    private static Set<String> tokens(String text) {
        text=text.replaceAll("\\b(?:terminal|nha ga|ga)\\s+(\\d+)\\b","t$1");
        text=text.replaceAll("\\b(?:trung tam thuong mai|truong dai hoc|san van dong|nha hat|ben xe|cong vien|benh vien|nha ga|cang hang khong quoc te|san bay quoc te|san bay|university|shopping mall|theatre|theater)\\b", " ");
        var result=new LinkedHashSet<String>();
        var stop=Set.of("nha","ga","noi","dia","terminal","san","bay","benh","vien","cho","gan","o","cua","thuoc","tai","the","of","airport","station","hospital","pho","tp","viet","nam");
        for(String word:text.split("[^a-z0-9]+")) if(!word.isBlank() && !stop.contains(word)) result.add(word);
        return result;
    }
    private static String norm(String value){return SystemKnowledgeService.normalize(value);}
    private static boolean contains(JsonNode box,NearbyLocation point) {
        return box.isArray() && box.size()==4 && box.get(0).isNumber() && box.get(1).isNumber() && box.get(2).isNumber() && box.get(3).isNumber()
                && point.longitude()>=box.get(0).asDouble() && point.longitude()<=box.get(2).asDouble()
                && point.latitude()<=box.get(1).asDouble() && point.latitude()>=box.get(3).asDouble();
    }
    private static boolean kindMatches(String query,JsonNode properties) {
        String key=properties.path("osm_key").asText(), value=properties.path("osm_value").asText();
        if(query.matches("^(?:(?:domestic|international)\\s+)?(?:nha ga|terminal|ga)\\b.*") || query.matches("t\\d+"))
            return "aeroway".equals(key)&&"terminal".equals(value) || "railway".equals(key)&&Set.of("station","halt").contains(value)
                    || "public_transport".equals(key)&&"station".equals(value);
        if(query.matches("^(?:san bay|airport|cang hang khong)\\b.*")) return "aeroway".equals(key)&&Set.of("aerodrome","terminal").contains(value);
        if(query.matches("^(?:benh vien|hospital)\\b.*")) return "amenity".equals(key)&&Set.of("hospital","clinic").contains(value);
        if(query.matches("^(?:truong dai hoc|university|dai hoc)\\b.*")) return "amenity".equals(key)&&Set.of("university","college","school").contains(value);
        if(query.matches("^(?:nha hat|theatre|theater)\\b.*")) return "amenity".equals(key)&&"theatre".equals(value);
        return true;
    }
    public static boolean valid(Double lat,Double lon){return lat!=null&&lon!=null&&Double.isFinite(lat)&&Double.isFinite(lon)&&Math.abs(lat)<=90&&Math.abs(lon)<=180&&!(lat==0&&lon==0);}
    public static double distance(Double lat1,Double lon1,Double lat2,Double lon2) {
        if(!valid(lat1,lon1)||!valid(lat2,lon2)) return Double.POSITIVE_INFINITY;
        double a=Math.pow(Math.sin(Math.toRadians(lat2-lat1)/2),2)+Math.cos(Math.toRadians(lat1))*Math.cos(Math.toRadians(lat2))*Math.pow(Math.sin(Math.toRadians(lon2-lon1)/2),2);
        return 6371.0088*2*Math.asin(Math.sqrt(Math.min(1,a)));
    }
}
